// Maps Vivid Life foundation tokens to a PowerShell theme script.
// One pure function: (flavor, variant, tokens) -> file content string.
//
// PowerShell's theme-able surface: PSReadLine's `Set-PSReadLineOption -Colors`
// (shell syntax highlighting + prediction list) and, on PowerShell 7.2+,
// `$PSStyle.Formatting.*` / `$PSStyle.FileInfo.*` (output formatting). There
// is no shell-wide ANSI terminal palette to set here; that belongs to the
// terminal emulator, out of scope for this port — same boundary the fish
// port draws. Requires PowerShell 7.2+ for `$PSStyle`; scripts no-op with a
// warning on older hosts.
//
// Property availability varies by PSReadLine/PowerShell version even within
// the 7.2+ baseline (e.g. PSReadLine 2.1.0, bundled with PowerShell 7.2,
// rejects `ListPrediction`/`ListPredictionSelected` — added in 2.2.0; some
// `$PSStyle.Formatting` members were added after 7.2 too). `Set-PSReadLineOption
// -Colors` applies its whole hashtable atomically, so one unsupported key
// throws and no color gets set at all. To stay correct across the version
// range, this template: (1) sends only empirically-verified-safe keys in the
// main `-Colors` call, (2) sends newer prediction keys in a second,
// try/catch-wrapped call, and (3) wraps every `$PSStyle.*` property
// assignment individually so one missing property doesn't block the rest.

import { rgbTriple } from "./rgb.mjs";

const label = {
  midnight: "Midnight",
  twilight: "Twilight",
  dawn: "Dawn",
  noon: "Noon",
};
const variantLabel = {
  red: "Red",
  orange: "Orange",
  yellow: "Yellow",
  green: "Green",
  blue: "Blue",
  purple: "Purple",
};

function fg(hex) {
  const [r, g, b] = rgbTriple(hex);
  return `$PSStyle.Foreground.FromRgb(${r}, ${g}, ${b})`;
}

function bg(hex) {
  const [r, g, b] = rgbTriple(hex);
  return `$PSStyle.Background.FromRgb(${r}, ${g}, ${b})`;
}

function resolveAccent(tokens, flavor, variant) {
  const shade = tokens.accent_shade[flavor][variant];
  return tokens.palette[variant][shade];
}

export function buildTheme(flavor, variant, tokens) {
  const f = tokens.flavors[flavor];
  const { text, state, semantic, syntax } = f;
  const accent = resolveAccent(tokens, flavor, variant);
  const name = `Vivid Life · ${label[flavor]} · ${variantLabel[variant]}`;

  // Verified against PSReadLine 2.1.0 (bundled with PowerShell 7.2, our
  // documented minimum) — all 16 keys accepted. Selection combines
  // foreground + background because PSReadLine's Selection color replaces
  // the rendering for the selected span outright rather than layering a
  // background over the token's own color (unlike fish's terminal-level
  // selection, which only needs a background) — this is also the pattern
  // Microsoft's own PSReadLine examples use.
  const coreColors = [
    ["Default", fg(text.fg)],
    ["Comment", fg(syntax.comment)],
    ["Keyword", fg(syntax.keyword)],
    ["String", fg(syntax.string)],
    ["Number", fg(syntax.number)],
    ["Command", fg(accent)],
    ["Parameter", fg(syntax.parameter)],
    ["Operator", fg(syntax.keyword)],
    ["Type", fg(syntax.type)],
    ["Variable", fg(syntax.constant)],
    ["Member", fg(syntax.function)],
    ["Emphasis", fg(semantic.info)],
    ["Error", fg(semantic.danger)],
    ["ContinuationPrompt", fg(text.fg_subtle)],
    ["InlinePrediction", fg(text.fg_subtle)],
    ["Selection", `${fg(text.fg)} + ${bg(state.selection)}`],
  ];

  // Requires PSReadLine 2.2.0+ — not present in the 2.1.0 baseline. Sent in
  // a separate, try/catch-wrapped call so an older PSReadLine still gets
  // every core color above.
  const predictionColors = [
    ["ListPrediction", fg(text.fg_muted)],
    ["ListPredictionSelected", `${fg(text.fg)} + ${bg(state.selection)}`],
  ];

  // $PSStyle.Formatting.* — output formatting (errors, tables, verbose/debug).
  // Property set has grown across PowerShell releases past 7.2 (e.g.
  // CustomTableHeaderLabel), so each assignment is wrapped individually.
  const formatting = [
    ["FormatAccent", fg(accent)],
    ["TableHeader", `$PSStyle.Bold + ${fg(accent)}`],
    ["CustomTableHeaderLabel", `$PSStyle.Bold + ${fg(accent)}`],
    ["Error", fg(semantic.danger)],
    ["ErrorAccent", `$PSStyle.Bold + ${fg(semantic.danger)}`],
    ["Warning", fg(semantic.warning)],
    ["Verbose", fg(semantic.info)],
    ["Debug", fg(text.fg_subtle)],
  ];

  // $PSStyle.FileInfo.* — directory listing accents (Get-ChildItem).
  const fileInfo = [
    ["Directory", `$PSStyle.Bold + ${fg(accent)}`],
    ["SymbolicLink", fg(syntax.constant)],
    ["Executable", fg(semantic.success)],
  ];

  const lines = [
    `# ${name}`,
    "# Generated by vivid-life-powershell — do not hand-edit. Edit src/theme-template.mjs and rebuild.",
    "",
    "if (-not $PSStyle) {",
    "    Write-Warning 'Vivid Life Theme requires PowerShell 7.2+ ($PSStyle). Skipping theme.'",
    "    return",
    "}",
    "",
    "& {",
    "    function Set-VividLifeProperty([scriptblock]$Assign) {",
    "        try { & $Assign } catch { }",
    "    }",
    "",
    "    if (Get-Module -ListAvailable -Name PSReadLine) {",
    "        Set-PSReadLineOption -Colors @{",
    ...coreColors.map(([key, value]) => `            ${key} = ${value}`),
    "        }",
    "",
    "        try {",
    "            Set-PSReadLineOption -Colors @{",
    ...predictionColors.map(
      ([key, value]) => `                ${key} = ${value}`,
    ),
    "            }",
    "        } catch { }",
    "    }",
    "",
    ...formatting.map(
      ([key, value]) =>
        `    Set-VividLifeProperty { $PSStyle.Formatting.${key} = ${value} }`,
    ),
    "",
    ...fileInfo.map(
      ([key, value]) =>
        `    Set-VividLifeProperty { $PSStyle.FileInfo.${key} = ${value} }`,
    ),
    "}",
    "",
  ];

  return lines.join("\n") + "\n";
}
